package dev.kyralabs.pingogram.core.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.luminance
import androidx.compose.ui.graphics.toArgb
import dev.kyralabs.pingogram.core.domain.model.Contrast
import dev.kyralabs.pingogram.core.domain.model.ThemePalette
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotEquals
import org.junit.jupiter.api.Assertions.assertSame
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.EnumSource
import kotlin.math.max
import kotlin.math.min

/**
 * The color themes generated by `tools/theme` (`docs/adr/0015-color-themes.md`): a snapshot of each one's seed and
 * primaries, so a change of seed, variant or generator shows here; and what Material asks of every scheme.
 */
class ThemePalettesTest {
    @Test
    fun `the generated themes are the documented ones`() {
        val snapshot =
            ThemePalette.entries.associateWith { palette ->
                Triple(
                    hex(paletteSeed(palette)),
                    hex(themeColorScheme(palette, dark = false, Contrast.Standard).primary),
                    hex(themeColorScheme(palette, dark = true, Contrast.Standard).primary),
                )
            }

        assertEquals(EXPECTED, snapshot)
    }

    @Test
    fun `Pingogram keeps the brand scheme the owner chose`() {
        val light = themeColorScheme(ThemePalette.Pingogram, dark = false, Contrast.Standard)

        assertEquals(Color(0xFF0055D6), light.primary)
        assertEquals(Color(0xFFFAF8FF), light.background)
        assertEquals(
            Color(0xFF10131C),
            themeColorScheme(ThemePalette.Pingogram, dark = true, Contrast.Standard).background,
        )
    }

    @Test
    fun `each theme's scheme is built once and kept`() {
        assertSame(
            themeColorScheme(ThemePalette.Orange, dark = true, Contrast.Medium),
            themeColorScheme(ThemePalette.Orange, dark = true, Contrast.Medium),
        )
    }

    @Test
    fun `every theme looks different`() {
        val primaries = ThemePalette.entries.map { themeColorScheme(it, dark = false, Contrast.Standard).primary }

        assertEquals(primaries.size, primaries.toSet().size)
    }

    @ParameterizedTest
    @EnumSource(ThemePalette::class)
    fun `light and dark schemes differ, dark with dark surfaces`(palette: ThemePalette) {
        val light = themeColorScheme(palette, dark = false, Contrast.Standard)
        val dark = themeColorScheme(palette, dark = true, Contrast.Standard)

        assertNotEquals(light.surface, dark.surface)
        assertTrue(dark.surface.luminance() < light.surface.luminance())
    }

    @ParameterizedTest
    @EnumSource(ThemePalette::class)
    fun `each contrast level raises the contrast of text and of the primary color`(palette: ThemePalette) {
        for (dark in listOf(false, true)) {
            val schemes = Contrast.entries.map { themeColorScheme(palette, dark, it) }
            val text = schemes.map { contrastRatio(it.onSurfaceVariant, it.surface) }
            val primary = schemes.map { contrastRatio(it.primary, it.surface) }

            assertTrue(text[0] < text[1] && text[1] < text[2], "$palette dark=$dark text $text")
            assertTrue(primary[0] <= primary[1] && primary[1] <= primary[2], "$palette dark=$dark primary $primary")
        }
    }

    @ParameterizedTest
    @EnumSource(ThemePalette::class)
    fun `text keeps Material's minimum contrast at the standard level`(palette: ThemePalette) {
        for (dark in listOf(false, true)) {
            val scheme = themeColorScheme(palette, dark, Contrast.Standard)
            for ((name, pair) in textPairs(scheme)) {
                val ratio = contrastRatio(pair.first, pair.second)
                assertTrue(ratio >= 4.5f, "$palette dark=$dark $name $ratio")
            }
        }
    }

    private fun textPairs(scheme: ColorScheme) =
        mapOf(
            "onSurface" to (scheme.onSurface to scheme.surface),
            "onSurfaceVariant" to (scheme.onSurfaceVariant to scheme.surface),
            "onPrimary" to (scheme.onPrimary to scheme.primary),
            "onPrimaryContainer" to (scheme.onPrimaryContainer to scheme.primaryContainer),
            "onSecondaryContainer" to (scheme.onSecondaryContainer to scheme.secondaryContainer),
            "onTertiaryContainer" to (scheme.onTertiaryContainer to scheme.tertiaryContainer),
        )

    private fun contrastRatio(
        first: Color,
        second: Color,
    ): Float {
        val lighter = max(first.luminance(), second.luminance())
        val darker = min(first.luminance(), second.luminance())
        return (lighter + 0.05f) / (darker + 0.05f)
    }

    private fun hex(color: Color) = "#%08X".format(color.toArgb())

    private companion object {
        /** Seed, light primary and dark primary of each theme, as `tools/theme` generated them. */
        val EXPECTED =
            mapOf(
                ThemePalette.Pingogram to Triple("#FF2156C4", "#FF0055D6", "#FFB3C5FF"),
                ThemePalette.Blue to Triple("#FF2196F3", "#FF36618E", "#FFA0CAFD"),
                ThemePalette.Teal to Triple("#FF009688", "#FF006A60", "#FF82D5C8"),
                ThemePalette.Green to Triple("#FF4CAF50", "#FF3B6939", "#FFA1D39A"),
                ThemePalette.Lime to Triple("#FFCDDC39", "#FF5C631D", "#FFC5CD7A"),
                ThemePalette.Yellow to Triple("#FFFFEB3B", "#FF685F12", "#FFD4C871"),
                ThemePalette.Orange to Triple("#FFFF9800", "#FF855318", "#FFFDB975"),
                ThemePalette.Red to Triple("#FFF44336", "#FF904A42", "#FFFFB4A9"),
                ThemePalette.Pink to Triple("#FFE91E63", "#FF8E4957", "#FFFFB2BE"),
                ThemePalette.Purple to Triple("#FF9C27B0", "#FF7B4E7F", "#FFEBB5ED"),
                ThemePalette.Indigo to Triple("#FF3F51B5", "#FF515B92", "#FFBAC3FF"),
                ThemePalette.Brown to Triple("#FF795548", "#FF8F4C33", "#FFFFB59A"),
                ThemePalette.Monochrome to Triple("#FF9E9E9E", "#FF000000", "#FFFFFFFF"),
            )
    }
}
