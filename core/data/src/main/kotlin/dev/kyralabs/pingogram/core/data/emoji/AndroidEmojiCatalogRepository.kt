package dev.kyralabs.pingogram.core.data.emoji

import android.content.Context
import android.graphics.Paint
import androidx.core.graphics.PaintCompat
import dagger.hilt.android.qualifiers.ApplicationContext
import dev.kyralabs.pingogram.core.common.Dispatcher
import dev.kyralabs.pingogram.core.common.PingogramDispatchers.Default
import dev.kyralabs.pingogram.core.data.R
import dev.kyralabs.pingogram.core.domain.model.EmojiCategory
import dev.kyralabs.pingogram.core.domain.model.EmojiGroup
import dev.kyralabs.pingogram.core.domain.repository.EmojiCatalogRepository
import kotlinx.collections.immutable.toImmutableList
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import javax.inject.Inject
import javax.inject.Singleton

/**
 * [EmojiCatalogRepository] on the bundled catalog, `res/raw/emoji_catalog.txt` (generated by `tools/emoji` from
 * Unicode's emoji data, Unicode License v3), read and filtered once per process on [dispatcher]. An emoji the device's
 * fonts cannot draw as one glyph (newer than its Android version) is left out ([PaintCompat.hasGlyph]), so the panel
 * never offers a box or a row of pieces.
 */
@Singleton
class AndroidEmojiCatalogRepository
    @Inject
    constructor(
        @param:ApplicationContext private val context: Context,
        @param:Dispatcher(Default) private val dispatcher: CoroutineDispatcher,
    ) : EmojiCatalogRepository {
        private val mutex = Mutex()
        private var catalog: List<EmojiGroup>? = null

        override suspend fun catalog(): List<EmojiGroup> =
            mutex.withLock {
                catalog ?: withContext(dispatcher) {
                    val text =
                        context.resources
                            .openRawResource(
                                R.raw.emoji_catalog,
                            ).bufferedReader()
                            .use { it.readText() }
                    val paint = Paint()
                    parseEmojiCatalog(text) { emoji -> PaintCompat.hasGlyph(paint, emoji) }
                }.also { catalog = it }
            }
    }

/**
 * The groups of the catalog [text]: one line per group, its slug, a tab and its emoji separated by spaces. Unknown
 * slugs (a newer catalog) and the emoji [isSupported] rejects are left out; the groups keep the catalog's order.
 */
internal fun parseEmojiCatalog(
    text: String,
    isSupported: (String) -> Boolean,
): List<EmojiGroup> =
    text
        .lineSequence()
        .mapNotNull { line ->
            val slug = line.substringBefore('\t', missingDelimiterValue = "")
            val category = CATEGORIES[slug] ?: return@mapNotNull null
            val emoji = line.substringAfter('\t').split(' ').filter { it.isNotEmpty() && isSupported(it) }
            EmojiGroup(category, emoji.toImmutableList())
        }.toList()

/** The catalog's group slugs (unicode-emoji-json's, from Unicode's group names). */
private val CATEGORIES =
    mapOf(
        "smileys_emotion" to EmojiCategory.SmileysAndEmotion,
        "people_body" to EmojiCategory.PeopleAndBody,
        "animals_nature" to EmojiCategory.AnimalsAndNature,
        "food_drink" to EmojiCategory.FoodAndDrink,
        "travel_places" to EmojiCategory.TravelAndPlaces,
        "activities" to EmojiCategory.Activities,
        "objects" to EmojiCategory.Objects,
        "symbols" to EmojiCategory.Symbols,
        "flags" to EmojiCategory.Flags,
    )
