package dev.kyralabs.pingogram.buildlogic

import org.w3c.dom.Element
import java.io.File
import javax.xml.parsers.DocumentBuilderFactory

/**
 * Which languages Pingogram ships (`docs/TRANSLATING.md`): English, the source language, and every language whose
 * translations cover at least [SHIP_THRESHOLD] of the translatable strings and plurals of all modules together. The
 * strings it lacks show in English. `pingogram.android.locales` turns the result into `:app`'s locale config and
 * resource filters, so a language appears in Settings → Language and in Android's app languages exactly when it ships.
 */
object Translations {
    /** The share of strings a language needs to ship: 80% (owner decision 2026-10-22). */
    const val SHIP_THRESHOLD = 0.8

    /** The source language, which every other is a translation of, as a BCP 47 tag. */
    const val SOURCE_LANGUAGE = "en"

    /**
     * The coverage of each translated language over [files], the `strings.xml` files of every `res/values*`
     * directory: for each resource directory, the names its `values/strings.xml` declares translatable, and the share of
     * them all that each `values-<language>/strings.xml` translates. Keyed by BCP 47 tag, sorted.
     */
    fun coverage(files: Iterable<File>): Map<String, Coverage> {
        val byResourceDirectory = files.groupBy { it.parentFile.parentFile }
        var total = 0
        val translated = sortedMapOf<String, Int>()
        for ((_, stringFiles) in byResourceDirectory) {
            val base = stringFiles.singleOrNull { it.parentFile.name == "values" } ?: continue
            val source = translatableNames(base.readText())
            total += source.size
            for (file in stringFiles) {
                val directory = file.parentFile.name
                if (!directory.startsWith("values-")) continue
                val language = languageTagOf(directory.removePrefix("values-")) ?: continue
                translated[language] = (translated[language] ?: 0) + (names(file.readText()) intersect source).size
            }
        }
        return translated.mapValues { (_, count) -> Coverage(count, total) }
    }

    /** The languages that ship: [SOURCE_LANGUAGE] first, then those [coverage] puts at or above [SHIP_THRESHOLD]. */
    fun shipped(coverage: Map<String, Coverage>): List<String> =
        listOf(SOURCE_LANGUAGE) +
            coverage.filter { (tag, it) -> tag != SOURCE_LANGUAGE && it.share >= SHIP_THRESHOLD }.keys.sorted()

    /**
     * The BCP 47 tag of a resource qualifier, or null if [qualifier] names no language: `de` → `de`, `pt-rBR` →
     * `pt-BR`, `b+sr+Latn` → `sr-Latn`. Other qualifiers (`night`, `v31`, `sw600dp`) are null.
     */
    fun languageTagOf(qualifier: String): String? =
        when {
            qualifier.startsWith("b+") -> qualifier.removePrefix("b+").replace('+', '-')
            LEGACY_QUALIFIER.matches(qualifier) -> qualifier.replace("-r", "-")
            else -> null
        }

    /** The resource qualifier of a BCP 47 [tag], as `localeFilters` take it: the reverse of [languageTagOf]. */
    fun qualifierOf(tag: String): String {
        val parts = tag.split('-')
        return when {
            parts.size == 1 -> parts[0]
            parts.size == 2 && parts[1].length == 2 && parts[1].all(Char::isUpperCase) -> "${parts[0]}-r${parts[1]}"
            else -> parts.joinToString("+", prefix = "b+")
        }
    }

    /** The `locales_config.xml` listing [tags] for Android 13+'s app languages and the app's Language page. */
    fun localeConfig(tags: List<String>): String =
        buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine(
                "<!-- Generated by pingogram.android.locales (docs/TRANSLATING.md): the languages Pingogram ships. -->",
            )
            appendLine("""<locale-config xmlns:android="http://schemas.android.com/apk/res/android">""")
            tags.forEach { appendLine("""    <locale android:name="$it" />""") }
            appendLine("</locale-config>")
        }

    /** The names of the strings and plurals in [xml] that are not marked `translatable="false"`. */
    fun translatableNames(xml: String): Set<String> =
        resources(xml).filter { it.getAttribute("translatable") != "false" }.map { it.getAttribute("name") }.toSet()

    /** The names of every string and plural in [xml]. */
    fun names(xml: String): Set<String> = resources(xml).map { it.getAttribute("name") }.toSet()

    private fun resources(xml: String): List<Element> {
        val document = DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(xml.byteInputStream())
        val root = document.documentElement
        return (0 until root.childNodes.length)
            .map(root.childNodes::item)
            .filterIsInstance<Element>()
            .filter { it.tagName == "string" || it.tagName == "plurals" }
    }

    // A language (two or three letters) with an optional region: "de", "fil", "pt-rBR".
    private val LEGACY_QUALIFIER = Regex("^[a-z]{2,3}(-r[A-Z]{2})?$")
}

/** How much of the source a language translates: [translated] of [total] strings and plurals. */
data class Coverage(
    val translated: Int,
    val total: Int,
) {
    val share: Double get() = if (total == 0) 0.0 else translated.toDouble() / total
}
